-- 0008_expense_enums.sql — 花費相關的列舉
--
-- 為什麼跟 0009 分開：Postgres 不允許在「新增 enum 值的同一個交易」裡使用那個
-- 新值。目前 0009 沒有用到，但拆開就完全不必去記這條規則。
-- =============================================================================

-- 刻意不沿用 activity_category：那是「地點的種類」，這是「付款的種類」。
-- 機票、簽證、網卡都不是地點，硬塞進去只會讓兩邊都變得不精確。
create type expense_category as enum (
  'food',      -- 餐飲
  'lodging',   -- 住宿
  'transport', -- 交通
  'ticket',    -- 門票、入場
  'shopping',  -- 購物
  'telecom',   -- 通訊：網卡、漫遊
  'other'      -- 其他
);

-- 花費的圖片用這個 role。
--
-- 名字叫 receipt 是歷史因素，實際語意是「屬於某筆花費的圖片」—— 不一定是
-- 收據，也可能是菜單、商品、或單純拍下來提醒自己買了什麼。介面上一律
-- 稱為「圖片」。
--
-- 之所以沒有改名或移除：這個值已經套用到正式資料庫、也已經有資料在用，
-- 而 Postgres 無法從 enum 移除既有的值。改動已套用的 migration 只會讓
-- 重建出來的資料庫跟正式環境對不起來。
alter type image_role add value 'receipt';
